import { serve } from "@hono/node-server";
import { Hono, type Context } from "hono";
import { randomUUID } from "node:crypto";
import { FAULTS, getFault } from "@plumberr/shared/faults";
import { getConfig, patchConfig, resetConfig } from "./config.js";
import { log, queryLogs } from "./logger.js";
import { clearSamples, httpDuration, httpRequests, record, registry, stats } from "./metrics.js";
import {
  HttpError, PRODUCTS, PricingError, cachePut, chargePayment, clearCache, fetchInventory, price, rateLimited, withDb,
} from "./domain.js";
import { addCommit, getCommit, listCommits } from "./commits.js";
import { initOrdersDb, queryOrders, syncIndex } from "./orders-db.js";
import { listRepoFiles, readRepoFile } from "./repo.js";

const PORT = Number(process.env.SHOP_PORT ?? process.env.PORT ?? 4100);
const INTERNAL_TOKEN = process.env.PLUMBERR_INTERNAL_TOKEN ?? "dev-internal-token-change-me";
/** Load is generated by the api (single service owns the loop); set >0 to self-drive in isolation. */
const LOADGEN_RPS = Number(process.env.SHOP_LOADGEN_RPS ?? 0);
const activeFaults = new Set<string>();

type Env = { Variables: { requestId: string } };
const app = new Hono<Env>();

/* ── request instrumentation (public routes only) ── */
app.use("*", async (c, next) => {
  const path = c.req.path;
  if (path.startsWith("/internal") || path === "/metrics" || path === "/health") return next();
  const requestId = c.req.header("x-request-id") ?? randomUUID();
  c.set("requestId", requestId);
  const start = performance.now();
  if (rateLimited()) {
    log.warn("rate limit exceeded", { route: path, status: 429, rpm: getConfig().ratelimit.rpm });
    c.res = c.json({ error: "rate limited" }, 429);
  } else {
    await next();
  }
  const ms = performance.now() - start;
  const route = c.req.routePath ?? path;
  const status = c.res.status;
  httpRequests.inc({ route, method: c.req.method, status: String(status) });
  httpDuration.observe({ route, method: c.req.method, status: String(status) }, ms / 1000);
  record(ms, status, route);
});

app.onError((err, c) => {
  const status = err instanceof HttpError ? err.status : 500;
  const stack = err instanceof PricingError ? err.frames : undefined;
  log.error("request failed", { route: c.req.path, status, err: `${err.name}: ${err.message}`, stack, requestId: c.get("requestId") });
  return c.json({ error: err.message }, status as 500);
});

/* ── public shop API ── */
app.get("/health", (c) => c.json({ ok: true }));
app.get("/products", (c) => c.json(PRODUCTS));
app.get("/products/:id", async (c) => {
  const p = PRODUCTS.find((x) => x.id === c.req.param("id"));
  if (!p) return c.json({ error: "not found" }, 404);
  const inventory = await fetchInventory(p.id);
  cachePut(p.id, c.get("requestId"));
  return c.json({ ...p, inventory });
});
app.get("/orders", async (c) => {
  const userId = Number(c.req.query("userId") ?? 1 + Math.floor(Math.random() * 50_000));
  const rows = await withDb(() => queryOrders(userId));
  return c.json(rows);
});
app.post("/checkout", async (c) => {
  const body = (await c.req.json().catch(() => ({}))) as { items?: string[]; coupon?: { percentOff: number } | null };
  const items = (body.items ?? ["1"]).map((id) => PRODUCTS.find((p) => p.id === id)).filter(Boolean);
  const total = items.reduce((s, p) => s + p!.priceCents, 0);
  const finalCents = price(total, body.coupon ?? null);
  const payment = await chargePayment(finalCents);
  log.info("checkout ok", { route: "/checkout", status: 200, amountCents: finalCents });
  return c.json({ ok: true, payment });
});

/* ── metrics ── */
app.get("/metrics", async (c) => c.text(await registry.metrics(), 200, { "content-type": registry.contentType }));

/* ── internal (fault injection + agent data sources), bearer-token protected ── */
const internal = new Hono();
internal.use("*", async (c, next) => {
  if (c.req.header("authorization") !== `Bearer ${INTERNAL_TOKEN}`) return c.json({ error: "unauthorized" }, 401);
  await next();
});
internal.get("/stats", (c) => c.json({ ...stats(), activeFaults: [...activeFaults], ts: new Date().toISOString() }));
internal.get("/config", (c) => c.json(getConfig()));
internal.get("/faults", (c) => c.json(FAULTS.map(({ id, title, description, mvp }) => ({ id, title, description, mvp, active: activeFaults.has(id) }))));
internal.post("/faults/:id", async (c) => {
  const fault = getFault(c.req.param("id"));
  if (!fault) return c.json({ error: "unknown fault" }, 404);
  const commit = addCommit({ author: "chaos-bot", message: fault.commit.message, files: fault.commit.files, diff: fault.commit.diff });
  patchConfig(fault.configPatch);
  await syncIndex();
  activeFaults.add(fault.id);
  log.warn("deploy", { sha: commit.sha.slice(0, 7), message: fault.commit.message, files: fault.commit.files });
  return c.json({ ok: true, fault: fault.id, commit });
});
internal.post("/reset", async (c) => {
  resetConfig();
  await syncIndex();
  clearCache();
  clearSamples(); // don't let the detector alert on pre-reset errors
  activeFaults.clear();
  log.info("config reset to baseline");
  return c.json({ ok: true, config: getConfig() });
});
internal.get("/logs", (c) =>
  c.json(
    queryLogs({
      level: c.req.query("level"),
      q: c.req.query("q"),
      sinceMinutes: Number(c.req.query("sinceMinutes") ?? 15),
      limit: Number(c.req.query("limit") ?? 50),
    }),
  ),
);
internal.get("/commits", (c) => c.json(listCommits(Number(c.req.query("sinceMinutes") ?? 60)).map(({ diff: _d, ...rest }) => rest)));
internal.get("/commits/:sha", (c: Context) => {
  const commit = getCommit(c.req.param("sha") ?? "");
  return commit ? c.json(commit) : c.json({ error: "not found" }, 404);
});
internal.get("/files", (c) => c.json(listRepoFiles()));
internal.get("/file", (c) => {
  const content = readRepoFile(c.req.query("path") ?? "");
  return content == null ? c.json({ error: "not found" }, 404) : c.json({ path: c.req.query("path"), content });
});
app.route("/internal", internal);

await initOrdersDb().catch((e: Error) => log.error("orders db init failed; using simulated /orders", { err: e.message }));
serve({ fetch: app.fetch, port: PORT }, (info) => {
  log.info(`demo-shop listening on :${info.port}`, { loadgenRps: LOADGEN_RPS });
});

/* ── built-in load generator: steady synthetic traffic so metrics are live ── */
if (LOADGEN_RPS > 0) {
  const self = `http://127.0.0.1:${PORT}`;
  setInterval(() => {
    const r = Math.random();
    const req =
      r < 0.4
        ? fetch(`${self}/products/${1 + Math.floor(Math.random() * 50)}`)
        : r < 0.7
          ? fetch(`${self}/orders`)
          : fetch(`${self}/checkout`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ items: ["1", "2"], coupon: null }) });
    req.then((res) => res.body?.cancel()).catch(() => {});
  }, 1000 / LOADGEN_RPS);
}
